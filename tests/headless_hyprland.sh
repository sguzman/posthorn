#!/usr/bin/env bash
# Experimental Arch/Hyprland compositor CI. No workstation or Mako cutover.
set -euo pipefail
[[ "\${POSTHORN_HEADLESS_HYPRLAND_TEST:-}" == "1" ]] || { echo 'Headless QA guard missing'; exit 1; }
[[ "\${GITHUB_ACTIONS:-}" == "true" ]] || { echo 'CI-only experimental harness'; exit 1; }
root="$(mktemp -d)"
hypr_pid=""
posthorn_pid=""
cleanup(){
  if [[ -n "$posthorn_pid" ]]; then kill "$posthorn_pid" 2>/dev/null || true; wait "$posthorn_pid" 2>/dev/null || true; fi
  if [[ -n "$hypr_pid" ]]; then kill "$hypr_pid" 2>/dev/null || true; wait "$hypr_pid" 2>/dev/null || true; fi
  rm -rf -- "$root"
}
trap cleanup EXIT
export XDG_RUNTIME_DIR="$root/runtime"
mkdir -p "$XDG_RUNTIME_DIR"
chmod 700 "$XDG_RUNTIME_DIR"
export HYPRLAND_NO_RT=1 HYPRLAND_NO_SD_NOTIFY=1 AQ_NO_KMS_REQUIREMENT=1
export LIBGL_ALWAYS_SOFTWARE=1 XDG_CURRENT_DESKTOP=Hyprland XDG_SESSION_TYPE=wayland
export XDG_CONFIG_HOME="$root/xdg"
mkdir -p "$XDG_CONFIG_HOME"
unset WAYLAND_DISPLAY HYPRLAND_INSTANCE_SIGNATURE || true

cat >"$root/hyprland.lua" <<'EOF'
hl.config({ autogenerated = false })
hl.monitor({ output = "HEADLESS-0", mode = "1280x720@60", position = "0x0", scale = 1 })
EOF
Hyprland --config "$root/hyprland.lua" >"$root/hyprland.log" 2>&1 &
hypr_pid=$!
socket=""
for _ in {1..80}; do
  for candidate in "$XDG_RUNTIME_DIR"/wayland-*; do
    if [[ -S "$candidate" ]]; then socket="$candidate"; break; fi
  done
  [[ -z "$socket" ]] || break
  if ! kill -0 "$hypr_pid" 2>/dev/null; then
    echo 'Headless Hyprland exited before Wayland socket'; cat "$root/hyprland.log"; exit 1
  fi
  sleep 0.25
done
[[ -n "$socket" ]] || { echo 'Missing headless Hyprland Wayland socket'; cat "$root/hyprland.log"; exit 1; }
export WAYLAND_DISPLAY="\${socket##*/}"
ready=0
for _ in {1..35}; do
  if timeout 5s grim "$root/before.png" >/dev/null 2>&1; then ready=1; break; fi
  sleep 0.2
done
[[ "$ready" == 1 ]] || {
  echo 'Headless Hyprland screenshot capture unavailable'
  cat "$root/hyprland.log"; exit 1
}
cat >"$root/posthorn.conf" <<'EOF'
width=320
height=96
margin=10
border-size=0
background-color=#1958AB
text-color=#FFFFFFFF
default-timeout=0
anchor=top-right
layer=overlay
EOF
./target/debug/posthorn --experimental-private-desktop "$root/posthorn.conf" \
  >"$root/posthorn.log" 2>&1 &
posthorn_pid=$!
ready=0
for _ in {1..45}; do
  if busctl --address="$DBUS_SESSION_BUS_ADDRESS" --timeout=2s call \
      org.freedesktop.DBus /org/freedesktop/DBus org.freedesktop.DBus \
      NameHasOwner s org.posthorn.Development 2>/dev/null | grep -q 'b true'; then
    ready=1; break
  fi
  if ! kill -0 "$posthorn_pid" 2>/dev/null; then
    echo 'Private Posthorn daemon exited'; cat "$root/posthorn.log"; exit 1
  fi
  sleep 0.2
done
[[ "$ready" == 1 ]] || { echo 'Private service did not acquire D-Bus name'; cat "$root/posthorn.log"; exit 1; }
reply="$(busctl --address="$DBUS_SESSION_BUS_ADDRESS" --timeout=5s call \
  org.posthorn.Development /org/freedesktop/Notifications org.freedesktop.Notifications \
  Notify 'susssasa{sv}i' 'Posthorn headless Hyprland QA' 0 '' \
  'Native compositor output' '' 0 0 30000)"
[[ "$reply" == u\ * ]] || { echo 'Unexpected private Notify reply'; exit 1; }
id="$(printf '%s\n' "$reply" | cut -d ' ' -f 2)"
painted=0
for _ in {1..35}; do
  timeout 5s grim "$root/visible.png"
  if ./target/debug/examples/qa_png_probe "$root/visible.png" '#1958AB' 500 increase \
      "$root/before.png" >/dev/null 2>&1; then painted=1; break; fi
  sleep 0.15
done
[[ "$painted" == 1 ]] || { echo 'Native Hyprland popup did not paint'; cat "$root/posthorn.log"; exit 1; }
busctl --address="$DBUS_SESSION_BUS_ADDRESS" --timeout=5s call \
  org.posthorn.Development /org/freedesktop/Notifications \
  org.freedesktop.Notifications CloseNotification u "$id" >/dev/null
removed=0
for _ in {1..35}; do
  timeout 5s grim "$root/after.png"
  if ./target/debug/examples/qa_png_probe "$root/after.png" '#1958AB' 60 restored \
      "$root/before.png" >/dev/null 2>&1; then removed=1; break; fi
  sleep 0.15
done
[[ "$removed" == 1 ]] || { echo 'Private popup remained after close'; cat "$root/posthorn.log"; exit 1; }
echo 'PASS: isolated headless Hyprland popup and private D-Bus lifecycle'
